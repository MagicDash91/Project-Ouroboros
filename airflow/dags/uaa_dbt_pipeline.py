"""
Universal AI Analytics — dbt pipeline (generated by the Data Engineer agent).

1. dbt_build     – rebuild every dbt model and run every dbt test
2. quality_gate  – summarise dbt's results and fail the run if any model or test failed.
                   (runs even if step 1 failed, so the summary is always in the logs)

dbt writes its artifacts to the shared dbt/uaa/target folder; the analytics app picks
them up from there, and dashboards read the marts live — no callback or network needed.
"""
import json
from datetime import datetime, timedelta

from airflow.providers.standard.operators.bash import BashOperator
from airflow.providers.standard.operators.python import PythonOperator
from airflow.sdk import DAG


def _quality_gate():
    with open("/opt/uaa/dbt/target/run_results.json", encoding="utf-8") as fh:
        results = json.load(fh)["results"]
    bad = [r for r in results if r["status"] not in ("success", "pass", "warn")]
    print(f"dbt: {len(results) - len(bad)}/{len(results)} models and tests OK")
    for r in bad:
        print(f"  FAILED {r['unique_id']}: {(r.get('message') or '')[:300]}")
    if bad:
        raise RuntimeError(f"{len(bad)} dbt node(s) failed")


with DAG(
    dag_id="uaa_dbt_pipeline",
    schedule='@daily',
    start_date=datetime(2026, 1, 1),
    catchup=False,
    max_active_runs=1,
    default_args={"retries": 1, "retry_delay": timedelta(minutes=5)},
    tags=["uaa", "dbt"],
) as dag:
    dbt_build = BashOperator(
        task_id="dbt_build",
        bash_command="cd /opt/uaa/dbt && dbt build --profiles-dir /opt/uaa/profiles --no-use-colors",
    )
    quality_gate = PythonOperator(task_id="quality_gate", python_callable=_quality_gate, trigger_rule="all_done")
    dbt_build >> quality_gate
