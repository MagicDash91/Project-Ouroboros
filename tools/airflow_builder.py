"""
tools/airflow_builder.py – Airflow orchestration for the dbt project.

Generates a self-contained Airflow 3 setup in airflow/ (Docker, because Airflow does not
run natively on Windows):
  * airflow       – `airflow standalone` (scheduler + API server + DAG processor) with
                    dbt-postgres installed; UI on http://localhost:8085
  * airflow-db    – Airflow's own metadata Postgres, internal to the Docker network only
                    (no host port, so it cannot collide with the native Postgres on 5432)
  * DAG uaa_dbt_pipeline – `dbt build` (models + tests) against the analytics database via
                    host.docker.internal, then calls the backend so the run is recorded.
                    Dashboards query the marts live, so they refresh automatically.

Secrets live only in airflow/.env and airflow/passwords.json (both git-ignored); the dbt
profile references the database password through env_var().
"""

import json
import os
import secrets
from pathlib import Path

import requests
import yaml
from sqlalchemy.engine import make_url

from features.deeper import _resolve_db_uri

BASE_DIR      = Path(__file__).resolve().parent.parent
AIRFLOW_DIR   = BASE_DIR / "airflow"
DAG_ID        = "uaa_dbt_pipeline"
AIRFLOW_URL   = os.getenv("AIRFLOW_URL", "http://localhost:8085")
AIRFLOW_USER  = "uaa"
AIRFLOW_IMAGE = "apache/airflow:3.2.1-python3.12"
SCHEDULES     = {"@hourly", "@daily", "@weekly", "@monthly", None}

_DOCKERFILE = f"""FROM {AIRFLOW_IMAGE}
# dbt runs inside the Airflow worker; pinned to the versions the backend uses.
RUN pip install --no-cache-dir "dbt-core==1.11.*" "dbt-postgres==1.10.*"
"""

_COMPOSE = {
    "name": "uaa-airflow",
    "services": {
        "airflow-db": {
            "image": "postgres:16-alpine",
            "environment": {"POSTGRES_USER": "airflow", "POSTGRES_PASSWORD": "airflow", "POSTGRES_DB": "airflow"},
            "volumes": ["airflow-db:/var/lib/postgresql/data"],
            "healthcheck": {"test": ["CMD", "pg_isready", "-U", "airflow"], "interval": "5s", "retries": 20},
            "restart": "unless-stopped",
        },
        "airflow": {
            "build": ".",
            "command": "standalone",
            "depends_on": {"airflow-db": {"condition": "service_healthy"}},
            "ports": ["8085:8080"],
            "env_file": [".env"],
            "environment": {
                "AIRFLOW__CORE__EXECUTOR": "LocalExecutor",
                "AIRFLOW__DATABASE__SQL_ALCHEMY_CONN": "postgresql+psycopg2://airflow:airflow@airflow-db/airflow",
                "AIRFLOW__CORE__LOAD_EXAMPLES": "False",
                "AIRFLOW__CORE__DAGS_ARE_PAUSED_AT_CREATION": "False",
                "AIRFLOW__CORE__SIMPLE_AUTH_MANAGER_USERS": f"{AIRFLOW_USER}:admin",
                "AIRFLOW__CORE__SIMPLE_AUTH_MANAGER_PASSWORDS_FILE": "/opt/airflow/passwords.json",
            },
            "volumes": [
                "./dags:/opt/airflow/dags",
                "./passwords.json:/opt/airflow/passwords.json",
                "../dbt/uaa:/opt/uaa/dbt",
                "./profiles:/opt/uaa/profiles:ro",
            ],
            "extra_hosts": ["host.docker.internal:host-gateway"],
            "restart": "unless-stopped",
        },
    },
    "volumes": {"airflow-db": {}},
}

_DAG = '''"""
Universal AI Analytics — dbt pipeline (generated by the Data Engineer agent).

1. dbt_build     – rebuild every dbt model and run every dbt test
2. quality_gate  – summarise dbt's results and fail the run if any model or test failed.
                   (runs even if step 1 failed, so the summary is always in the logs)

dbt writes its artifacts to the shared dbt/uaa/target folder; the analytics app picks
them up from there, and dashboards read the marts live — no callback or network needed.
"""
import json
from datetime import datetime, timedelta

from airflow.providers.standard.operators.bash import BashOperator
from airflow.providers.standard.operators.python import PythonOperator
from airflow.sdk import DAG


def _quality_gate():
    with open("/opt/uaa/dbt/target/run_results.json", encoding="utf-8") as fh:
        results = json.load(fh)["results"]
    bad = [r for r in results if r["status"] not in ("success", "pass", "warn")]
    print(f"dbt: {len(results) - len(bad)}/{len(results)} models and tests OK")
    for r in bad:
        print(f"  FAILED {r['unique_id']}: {(r.get('message') or '')[:300]}")
    if bad:
        raise RuntimeError(f"{len(bad)} dbt node(s) failed")


with DAG(
    dag_id="__DAG_ID__",
    schedule=__SCHEDULE__,
    start_date=datetime(2026, 1, 1),
    catchup=False,
    max_active_runs=1,
    default_args={"retries": 1, "retry_delay": timedelta(minutes=5)},
    tags=["uaa", "dbt"],
) as dag:
    dbt_build = BashOperator(
        task_id="dbt_build",
        bash_command="cd /opt/uaa/dbt && dbt build --profiles-dir /opt/uaa/profiles --no-use-colors",
    )
    quality_gate = PythonOperator(task_id="quality_gate", python_callable=_quality_gate, trigger_rule="all_done")
    dbt_build >> quality_gate
'''


def _read_env() -> dict:
    p = AIRFLOW_DIR / ".env"
    if not p.exists():
        return {}
    out = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def write_setup(schedule: str = "@daily", db_uri: str = "") -> dict:
    """(Re)generate the Airflow project files. Does not start Docker."""
    if schedule not in SCHEDULES:
        raise ValueError(f"schedule must be one of {sorted(s for s in SCHEDULES if s)} or None")
    uri = make_url(_resolve_db_uri(db_uri))
    if not uri.drivername.startswith("postgres"):
        raise ValueError("Airflow orchestration needs the PostgreSQL analytics database.")

    (AIRFLOW_DIR / "dags").mkdir(parents=True, exist_ok=True)
    (AIRFLOW_DIR / "profiles").mkdir(parents=True, exist_ok=True)
    (AIRFLOW_DIR / ".gitignore").write_text(".env\npasswords.json\nlogs/\n", encoding="utf-8")
    (AIRFLOW_DIR / "Dockerfile").write_text(_DOCKERFILE, encoding="utf-8")
    (AIRFLOW_DIR / "docker-compose.yml").write_text(yaml.safe_dump(_COMPOSE, sort_keys=False), encoding="utf-8")

    host = uri.host or "localhost"
    if host in ("localhost", "127.0.0.1", "::1"):
        host = "host.docker.internal"          # the container reaches the Windows host this way
    target = {"type": "postgres", "host": host, "port": int(uri.port or 5432), "user": uri.username or "postgres",
              "password": "{{ env_var('UAA_DBT_PASSWORD') }}", "dbname": uri.database, "schema": "uaa",
              "threads": 4, "connect_timeout": 15}
    if uri.query.get("sslmode"):                     # e.g. Supabase requires SSL
        target["sslmode"] = uri.query["sslmode"]
    (AIRFLOW_DIR / "profiles" / "profiles.yml").write_text(yaml.safe_dump(
        {"uaa": {"target": "dev", "outputs": {"dev": target}}}, sort_keys=False), encoding="utf-8")

    env = _read_env()
    airflow_pw = env.get("UAA_AIRFLOW_PASSWORD") or secrets.token_urlsafe(18)
    (AIRFLOW_DIR / ".env").write_text(
        f"UAA_DBT_PASSWORD={uri.password or ''}\nUAA_AIRFLOW_PASSWORD={airflow_pw}\n", encoding="utf-8")
    (AIRFLOW_DIR / "passwords.json").write_text(json.dumps({AIRFLOW_USER: airflow_pw}), encoding="utf-8")

    dag = _DAG.replace("__DAG_ID__", DAG_ID).replace("__SCHEDULE__", repr(schedule))
    (AIRFLOW_DIR / "dags" / f"{DAG_ID}.py").write_text(dag, encoding="utf-8")
    return {"dir": str(AIRFLOW_DIR), "dag_id": DAG_ID, "schedule": schedule, "ui_url": AIRFLOW_URL,
            "login": {"user": AIRFLOW_USER, "password_file": str(AIRFLOW_DIR / ".env")},
            "start_command": f'docker compose -f "{AIRFLOW_DIR / "docker-compose.yml"}" up -d --build'}


# ── Airflow REST API (v2) ─────────────────────────────────────────────────────

def _token() -> str:
    pw = _read_env().get("UAA_AIRFLOW_PASSWORD")
    if not pw:
        raise RuntimeError("Airflow is not set up yet")
    r = requests.post(f"{AIRFLOW_URL}/auth/token", json={"username": AIRFLOW_USER, "password": pw}, timeout=10)
    r.raise_for_status()
    return r.json()["access_token"]


def _api(method: str, path: str, **kw):
    r = requests.request(method, f"{AIRFLOW_URL}/api/v2{path}",
                         headers={"Authorization": f"Bearer {_token()}"}, timeout=15, **kw)
    r.raise_for_status()
    return r.json()


def status() -> dict:
    if not (AIRFLOW_DIR / "docker-compose.yml").exists():
        return {"configured": False, "reachable": False,
                "message": "Airflow is not set up yet. Generate the setup, then start it with Docker."}
    try:
        from tools.dbt_builder import sync_external_results
        sync_external_results("airflow")       # pick up dbt results the container produced
    except Exception:
        pass
    try:
        dag = _api("GET", f"/dags/{DAG_ID}")
        runs = _api("GET", f"/dags/{DAG_ID}/dagRuns", params={"order_by": "-start_date", "limit": 8})
    except Exception as e:
        return {"configured": True, "reachable": False, "ui_url": AIRFLOW_URL,
                "message": f"Airflow is set up but not reachable at {AIRFLOW_URL}. Start it with "
                           f"`docker compose up -d` in {AIRFLOW_DIR}. ({str(e)[:160]})"}
    return {
        "configured": True, "reachable": True, "ui_url": AIRFLOW_URL, "dag_id": DAG_ID,
        "schedule": dag.get("timetable_summary") or dag.get("timetable_description"),
        "paused": dag.get("is_paused"),
        "runs": [{"run_id": r.get("dag_run_id"), "state": r.get("state"), "start": r.get("start_date"),
                  "end": r.get("end_date"), "trigger": r.get("run_type")} for r in runs.get("dag_runs", [])],
    }


def trigger() -> dict:
    run = _api("POST", f"/dags/{DAG_ID}/dagRuns", json={"logical_date": None})
    return {"dag_run_id": run.get("dag_run_id"), "state": run.get("state")}
